"""Read-only, bounded repository/data inspection. No candidate code is executed."""
import ast
import csv
import hashlib
import json
from pathlib import Path

SKIP={'.git','.venv','venv','node_modules','__pycache__','.pytest_cache','oracle','reference'}


def inspect_source(root):
    root=Path(root).resolve()
    if not root.is_dir():raise ValueError('source must be a directory')
    code=[];datasets=[];skipped=[]
    for path in sorted(root.rglob('*')):
        rel=path.relative_to(root)
        if any(p in SKIP or p.startswith('.') for p in rel.parts):continue
        if path.is_symlink() or any(p.is_symlink() for p in path.parents if p!=root and root in p.parents):
            skipped.append(str(rel));continue
        if not path.is_file() or path.suffix not in ('.py','.json','.csv'):continue
        if path.stat().st_size>2*1024*1024:skipped.append(str(rel));continue
        try:
            if path.suffix=='.py':
                tree=ast.parse(path.read_text());functions=[n.name for n in tree.body if isinstance(n,ast.FunctionDef)]
                code.append(dict(path=str(rel),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),functions=functions,transform_entrypoint='transform' in functions))
            elif path.suffix=='.csv':
                with path.open(newline='') as f:
                    reader=csv.DictReader(f);rows=[]
                    for i,row in enumerate(reader):
                        if i>=500:break
                        rows.append(row)
                    fields=reader.fieldnames or []
                datasets.append(dict(path=str(rel),format='csv',sampled_rows=len(rows),columns=fields,null_counts={k:sum(not r.get(k) for r in rows) for k in fields},sampling_limit=500))
            else:
                value=json.loads(path.read_text());datasets.append(dict(path=str(rel),format='json',top_level_type=type(value).__name__,records=len(value) if isinstance(value,list) else None,keys=sorted(value) if isinstance(value,dict) else None))
        except (ValueError,SyntaxError,UnicodeError,csv.Error) as exc:skipped.append(dict(path=str(rel),reason=type(exc).__name__))
    needs=['A written input/output contract, including nulls, duplicates, ordering, timezones, and rounding rules.',
           'Evidence of rights to redistribute code and representative data; synthetic replacements for restricted customer data.',
           'Independently authored expected outputs and edge cases, not labels generated by executing the reference fix.',
           'A known failing starting state and a reviewed working reference implementation.',
           'A family or repository grouping for train/validation/test splits, plus leakage review.']
    return dict(schema_version='1.0',code=code,datasets=datasets,skipped=skipped,
                candidate_entrypoints=[c['path'] for c in code if c['transform_entrypoint']],
                readiness='manual_contract_review_required',lab_needs=needs,
                note='Structural suitability only. Inspection cannot infer business correctness or licensing permission. No source code was executed and no raw data values are included.')
